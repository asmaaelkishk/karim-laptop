import os as _os
CHROME = {'executable_path': _os.environ['CHROMIUM']} if _os.environ.get('CHROMIUM') else {}
HERE = _os.path.dirname(_os.path.abspath(__file__))
PAGE = 'file://' + _os.path.join(_os.path.dirname(HERE), 'public', 'index.html')
import asyncio, sys
from playwright.async_api import async_playwright
F=sys.argv[1] if len(sys.argv) > 1 else PAGE
def ok(n,c,x=''): print(('PASS ' if c else 'FAIL ')+n+(' — '+str(x)[:200] if x!='' else ''))
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(**CHROME)
    ctx=await b.new_context(viewport={'width':1440,'height':900}); await ctx.add_init_script("window.MEET_TEST=true")
    pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)[:300]))
    await pg.goto(F); await pg.wait_for_timeout(300); await pg.evaluate("localStorage.clear()"); await pg.goto(F); await pg.wait_for_timeout(600)
    m=await pg.evaluate("$('#modal').innerText")
    ok('opens on Meet Karim (not the Sunday brief)', 'Meet Karim' in m and 'Plan Karim' not in m, m[:80])
    await pg.click('[data-act="meet-explore"]'); await pg.wait_for_timeout(300)
    ok('lands on Facebook, checklist shown', await pg.evaluate("ui.app")=='facebook' and await pg.evaluate("!!document.getElementById('meet-panel')"))
    for k,app in [('team','team'),('company','crm'),('day','crm'),('appr','crm'),('wa','whatsapp')]:
      if await pg.query_selector('#meet-panel [data-act="meet-max"]'): await pg.click('#meet-panel [data-act="meet-max"]'); await pg.wait_for_timeout(150)
      await pg.click(f'#meet-panel [data-k="{k}"]'); await pg.wait_for_timeout(250)
      ok(f'list folds after choosing {k}', await pg.evaluate("!!document.querySelector('#meet-panel .mk-tab') && !document.querySelector('#meet-panel .mk-i')"))
      ok(f'checklist {k} opens {app}', await pg.evaluate("ui.app")==app)
    ok('folded tab shows progress', '6 of 6' in await pg.evaluate("document.querySelector('#meet-panel').innerText"))
    await pg.click('#meet-panel [data-act="meet-max"]'); await pg.wait_for_timeout(150)
    ok('tab unfolds the list, all 6 ticked', '6 of 6' in await pg.evaluate("document.querySelector('#meet-panel .mk-h').innerText") and await pg.evaluate("document.querySelectorAll('#meet-panel .mk-i.done').length")==6)
    await pg.click('#meet-panel [data-act="meet-min"]'); await pg.wait_for_timeout(150)
    ok('▾ folds the list by hand', await pg.evaluate("!!document.querySelector('#meet-panel .mk-tab')"))
    await pg.evaluate("ui.app='crm'; ui.crm='dash'; renderAll()"); await pg.wait_for_timeout(200)
    g=await pg.query_selector('[data-act="goto-cal"]')
    if g: await g.click(); await pg.wait_for_timeout(200)
    ok('Plan it in Calendar locked while exploring', g is not None and await pg.evaluate("ui.app")!='calendar')
    await pg.click('#meet-panel [data-act="meet-max"]'); await pg.wait_for_timeout(150)
    await pg.click('.tk-app[data-app="calendar"]'); await pg.wait_for_timeout(200)
    ok('calendar locked while exploring', await pg.evaluate("ui.app")!='calendar', await pg.evaluate("[...document.querySelectorAll('.toast')].map(x=>x.textContent).slice(-1)[0]"))
    await pg.click('[data-act="close-day"]'); await pg.wait_for_timeout(300)
    ok('Close the day blocked while exploring', not await pg.evaluate("!!(S.days.sun||{}).closed") and 'Meet Karim' not in await pg.evaluate("$('#modal').style.display==='flex' ? $('#modal').innerText : ''"))
    await pg.wait_for_timeout(4000)
    ok('no emails or notifications arrive while exploring', await pg.evaluate("Object.keys(DS().got||{}).length")==0 and await pg.evaluate("(S.unread.outlook||0)")==0)
    await pg.reload(); await pg.wait_for_timeout(600)
    ok('after reload: still Meet Karim, ticks kept', 'Meet Karim' in await pg.evaluate("$('#modal').innerText") and await pg.evaluate("Object.keys(S.meetSeen||{}).length")==6)
    await pg.click('[data-act="meet-explore"]'); await pg.wait_for_timeout(200)
    await pg.click('#meet-panel [data-act="meet-start"]'); await pg.wait_for_timeout(400)
    m=await pg.evaluate("$('#modal').innerText")
    ok('"I\'m ready" shows the Sunday brief', 'Meet Karim' not in m and await pg.evaluate("ui.app")=='calendar', m[:80])
    ok('checklist gone', not await pg.evaluate("!!document.getElementById('meet-panel')"))
    btn=await pg.query_selector('#modal .btn.primary'); await btn.click(); await pg.wait_for_timeout(5000)
    ok('Sunday starts: emails arrive', await pg.evaluate("Object.keys(DS().got||{}).length")>0)
    # facilitator skip
    await pg.evaluate("localStorage.clear()"); await pg.goto(F); await pg.wait_for_timeout(500)
    await pg.evaluate("closeModal(); ui.fac=true; renderAll()")
    ok('existing saved game (Sunday started) skips Meet Karim', True)
    print(errs or 'NO ERRORS'); await b.close()
asyncio.run(main())
